let lang = 'ru';

function setLanguage(l) {
    lang = (l === 'en' || l === 'ru') ? l : 'ru';
}

function t(key, params) {
    let s = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
    if (params) {
        for (const [name, value] of Object.entries(params)) {
            s = s.split(`{${name}}`).join(String(value));
        }
    }
    return s;
}

module.exports = { setLanguage, t };
